import Foundation
import SwiftProtobuf
import SwiftProtobufPluginLibrary

@main
struct OmniBufSwiftPlugin: CodeGenerator {
    var version: String? { "0.1.0" }
    var projectURL: String? { "https://github.com/omnibuf/omnibuf-swift" }
    var copyrightLine: String? { "Copyright 2026 Kevin McDonald" }

    var supportedFeatures: [Google_Protobuf_Compiler_CodeGeneratorResponse.Feature] {
        [.proto3Optional]
    }

    init() {}

    func generate(
        files: [FileDescriptor],
        parameter: any CodeGeneratorParameter,
        protoCompilerContext: any ProtoCompilerContext,
        generatorOutputs: any GeneratorOutputs
    ) throws {
        for file in files {
            let outputName = outputFileName(for: file.name)
            let code = generateFile(file)
            try generatorOutputs.add(fileName: outputName, contents: code)
        }
    }

    private func outputFileName(for protoName: String) -> String {
        if protoName.hasSuffix(".proto") {
            return String(protoName.dropLast(6)) + ".omnibuf.swift"
        }
        return protoName + ".omnibuf.swift"
    }

    private func generateFile(_ file: FileDescriptor) -> String {
        var out = ""
        out += "// DO NOT EDIT.\n"
        out += "// swift-format-ignore-file\n"
        out += "// Generated by protoc-gen-omnibuf-swift from \(file.name)\n\n"
        out += "import OmniBuf\n\n"

        for e in file.enums {
            emitEnum(e, into: &out, indent: "")
        }
        for msg in file.messages {
            emitMessage(msg, into: &out, indent: "")
        }
        return out
    }

    // MARK: - Naming Helpers

    private func swiftTypeName(_ descriptor: Descriptor) -> String {
        descriptor.name
    }

    private func swiftEnumName(_ descriptor: EnumDescriptor) -> String {
        descriptor.name
    }

    private func camelCaseRaw(_ snake: String) -> String {
        let leadingUnderscores = snake.prefix(while: { $0 == "_" })
        let parts = snake.split(separator: "_")
        guard let first = parts.first else {
            return snake.isEmpty ? "_" : snake
        }
        var res = String(leadingUnderscores) + first.lowercased()
        for p in parts.dropFirst() {
            res += p.prefix(1).uppercased() + p.dropFirst().lowercased()
        }
        if let firstChar = res.first, firstChar.isNumber {
            res = "_" + res
        }
        return res
    }

    private func camelCase(_ snake: String) -> String {
        escapeKeyword(camelCaseRaw(snake))
    }

    private func pascalCase(_ snake: String) -> String {
        let parts = snake.split(separator: "_")
        guard !parts.isEmpty else { return snake }
        return parts.map { part in
            part.prefix(1).uppercased() + part.dropFirst().lowercased()
        }.joined()
    }

    private func escapeKeyword(_ name: String) -> String {
        let keywords: Set<String> = [
            "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func",
            "import", "init", "inout", "internal", "let", "open", "operator", "private",
            "protocol", "Protocol", "public", "static", "struct", "subscript", "typealias", "var",
            "break", "case", "continue", "default", "defer", "do", "else", "fallthrough",
            "for", "guard", "if", "in", "repeat", "return", "switch", "where", "while",
            "as", "Any", "any", "some", "none", "async", "await", "Type", "catch", "false",
            "is", "nil", "rethrows", "super", "self", "Self", "throw", "throws", "true", "try",
            "precedencegroup", "borrowing", "consuming", "nonisolated", "isolated", "actor",
            "macro", "package", "description",
        ]
        return keywords.contains(name) ? "`\(name)`" : name
    }

    // MARK: - Enum Generation

    private func emitEnum(_ e: EnumDescriptor, into out: inout String, indent: String) {
        let name = swiftEnumName(e)
        out += "\(indent)public enum \(name): Int32, Sendable, Equatable, Hashable {\n"
        var seenRawValues: [Int32: String] = [:]
        for val in e.values {
            let caseName = camelCase(val.name)
            if let existingCase = seenRawValues[val.number] {
                out += "\(indent)    public static let \(caseName): \(name) = .\(existingCase)\n"
            } else {
                seenRawValues[val.number] = caseName
                out += "\(indent)    case \(caseName) = \(val.number)\n"
            }
        }
        out += "\(indent)    public init() { self = .\(camelCase(e.values.first?.name ?? "unspecified")) }\n"
        out += "\(indent)}\n\n"
    }

    // MARK: - Field Type Mapping

    private func swiftFieldType(_ field: FieldDescriptor) -> String {
        if field.isMap {
            let entry = field.messageType!
            let kType = swiftScalarType(entry.fields[0])
            let vField = entry.fields[1]
            let vType = swiftSingularBaseType(vField)
            return "[\(kType): \(vType)]"
        }
        if field.isRepeated {
            return "[\(swiftSingularBaseType(field))]"
        }
        if field.type == .message {
            return "\(swiftTypeName(field.messageType!))?"
        }
        return swiftSingularBaseType(field)
    }

    private func swiftSingularBaseType(_ field: FieldDescriptor) -> String {
        if field.type == .message {
            return swiftTypeName(field.messageType!)
        }
        if field.type == .enum {
            return "Int32"
        }
        return swiftScalarType(field)
    }

    private func swiftScalarType(_ field: FieldDescriptor) -> String {
        switch field.type {
        case .uint32, .fixed32: return "UInt32"
        case .uint64, .fixed64: return "UInt64"
        case .int32, .sint32, .sfixed32: return "Int32"
        case .int64, .sint64, .sfixed64: return "Int64"
        case .bool: return "Bool"
        case .float: return "Float"
        case .double: return "Double"
        case .string: return "String"
        case .bytes: return "[UInt8]"
        default: return "Int32"
        }
    }

    private func defaultValue(_ field: FieldDescriptor) -> String {
        if field.isMap { return "[:]" }
        if field.isRepeated { return "[]" }
        switch field.type {
        case .message: return "nil"
        case .bool: return "false"
        case .string: return "\"\""
        case .bytes: return "[]"
        case .float, .double: return "0"
        default: return "0"
        }
    }

    private func wireTypeExpr(_ field: FieldDescriptor) -> String {
        switch field.type {
        case .uint32, .uint64: return "WireType.wireUint"
        case .int32, .int64, .sint32, .sint64, .enum: return "WireType.wireSint"
        case .bool: return "WireType.wireBoolFalse"
        case .fixed32: return "WireType.wireFixed32"
        case .fixed64: return "WireType.wireFixed64"
        case .sfixed32: return "WireType.wireSfixed32"
        case .sfixed64: return "WireType.wireSfixed64"
        case .float: return "WireType.wireFloat32"
        case .double: return "WireType.wireFloat64"
        case .string: return "WireType.wireString"
        case .bytes: return "WireType.wireBytes"
        case .message: return "WireType.wireSubMsg"
        default: return "WireType.wireUint"
        }
    }

    // MARK: - Message Generation

    private func emitMessage(_ msg: Descriptor, into out: inout String, indent: String) {
        if msg.options.mapEntry { return }

        for nested in msg.messages where !nested.options.mapEntry {
            emitMessage(nested, into: &out, indent: indent)
        }
        for nestedEnum in msg.enums {
            emitEnum(nestedEnum, into: &out, indent: indent)
        }

        let name = swiftTypeName(msg)
        let fields = msg.fields.sorted { $0.number < $1.number }

        // Struct declaration
        out += "\(indent)public struct \(name): OmniBufMessage, Equatable, Sendable {\n"
        for f in fields {
            out += "\(indent)    public var \(camelCase(f.name)): \(swiftFieldType(f))\n"
        }
        if fields.isEmpty {
            out += "\n\(indent)    public init() {}\n\n"
        } else {
            out += "\n\(indent)    public init(\n"
            for (i, f) in fields.enumerated() {
                let comma = i + 1 < fields.count ? "," : ""
                out += "\(indent)        \(camelCase(f.name)): \(swiftFieldType(f)) = \(defaultValue(f))\(comma)\n"
            }
            out += "\(indent)    ) {\n"
            for f in fields {
                let p = camelCase(f.name)
                out += "\(indent)        self.\(p) = \(p)\n"
            }
            out += "\(indent)    }\n\n"
            out += "\(indent)    public init() {\n"
            out += "\(indent)        self.init(\(camelCase(fields[0].name)): \(defaultValue(fields[0])))\n"
            out += "\(indent)    }\n\n"
        }

        // Fast O(fields) size hint for single-allocation encoding and 4B length pre-sizing
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public var estimatedOmniBufSize: Int {\n"
        out += "\(indent)        var n = \(max(fields.count * 4, 16))\n"
        for f in fields {
            let p = camelCase(f.name)
            if f.isMap {
                out += "\(indent)        n &+= \(p).count &* 24\n"
            } else if f.isRepeated {
                if f.type == .string {
                    out += "\(indent)        for s in \(p) { n &+= s.utf8.count &+ 4 }\n"
                } else if f.type == .bytes {
                    out += "\(indent)        for b in \(p) { n &+= b.count &+ 4 }\n"
                } else if f.type == .message {
                    out += "\(indent)        for m in \(p) { n &+= m.estimatedOmniBufSize &+ 4 }\n"
                } else {
                    out += "\(indent)        n &+= \(p).count &* 8\n"
                }
            } else if f.type == .string {
                out += "\(indent)        n &+= \(p).utf8.count\n"
            } else if f.type == .bytes {
                out += "\(indent)        n &+= \(p).count\n"
            } else if f.type == .message {
                out += "\(indent)        if let m = \(p) { n &+= m.estimatedOmniBufSize &+ 4 }\n"
            }
        }
        out += "\(indent)        return n\n"
        out += "\(indent)    }\n\n"

        // Fast marshalOmniBuf() convenience
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public func marshalOmniBuf() -> [UInt8] {\n"
        out += "\(indent)        var w = OmniBufWriter(initialCapacity: max(256, estimatedOmniBufSize))\n"
        out += "\(indent)        encodeOmniBufBodyFast(into: &w, deterministic: true)\n"
        out += "\(indent)        return w.toBytes()\n"
        out += "\(indent)    }\n\n"

        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public func encodeOmniBufBody(into writer: inout OmniBufWriter, options: EncodeOptions) throws {\n"
        out += "\(indent)        encodeOmniBufBodyFast(into: &writer, deterministic: options.deterministic)\n"
        out += "\(indent)    }\n\n"

        // Fast single-pass encoder
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public func encodeOmniBufBodyFast(into w: inout OmniBufWriter, deterministic: Bool) {\n"
        for f in fields {
            emitEncodeField(f, target: "self.\(camelCase(f.name))", into: &out, indent: indent + "        ")
        }
        out += "\(indent)    }\n\n"

        // Fast decoder (merge mode)
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public mutating func mergeOmniBuf(from data: UnsafeBufferPointer<UInt8>, depth: Int, budget: inout DecodeBudget) throws {\n"
        out += "\(indent)        guard depth <= budget.maxDepth else {\n"
        out += "\(indent)            throw OmniBufError.depthLimitExceeded(depth)\n"
        out += "\(indent)        }\n"
        out += "\(indent)        var r = OmniBufReader(data)\n"
        out += "\(indent)        while !r.isAtEnd {\n"
        out += "\(indent)            let (fnum, wt) = try r.readTag()\n"
        out += "\(indent)            switch fnum {\n"
        out += "\(indent)            case 0:\n"
        out += "\(indent)                guard wt == WireType.wireSubMsg else {\n"
        out += "\(indent)                    throw OmniBufError.parse(\"Field #0 must have WireSubMsg (12), got \\(wt)\")\n"
        out += "\(indent)                }\n"
        out += "\(indent)                let slice = try r.readLenSlice()\n"
        out += "\(indent)                _ = try SchemaMeta.validateSlice(slice, depth: depth &+ 1, maxDepth: budget.maxDepth)\n"
        for f in fields {
            emitDecodeField(f, into: &out, indent: indent + "            ")
        }
        out += "\(indent)            default:\n"
        out += "\(indent)                try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
        out += "\(indent)            }\n"
        out += "\(indent)        }\n"
        out += "\(indent)    }\n\n"

        // Field #0 SchemaMeta (cycle-safe for self- and mutually-recursive messages)
        out += "\(indent)    public static var omniBufSchemaMeta: SchemaMeta {\n"
        out += "\(indent)        var visited: Set<String> = []\n"
        out += "\(indent)        return buildOmniBufSchemaMeta(visited: &visited)\n"
        out += "\(indent)    }\n\n"
        out += "\(indent)    public static func buildOmniBufSchemaMeta(visited: inout Set<String>) -> SchemaMeta {\n"
        out += "\(indent)        var fields: [UInt32: String] = [:]\n"
        var hasChildMeta = false
        for f in fields {
            if f.isMap {
                let vField = f.messageType!.fields[1]
                if vField.type == .message {
                    hasChildMeta = true
                }
            } else if f.type == .message {
                hasChildMeta = true
            }
        }
        out += "\(indent)        \(hasChildMeta ? "var" : "let") children: [UInt32: SchemaMeta] = [:]\n"
        if hasChildMeta {
            out += "\(indent)        let typeKey = \"\(msg.fullName)\"\n"
            out += "\(indent)        let inserted = visited.insert(typeKey).inserted\n"
            out += "\(indent)        defer { if inserted { visited.remove(typeKey) } }\n"
        }
        for f in fields {
            out += "\(indent)        fields[\(f.number)] = \"\(f.name)\"\n"
            if f.isMap {
                let vField = f.messageType!.fields[1]
                if vField.type == .message {
                    out += "\(indent)        if inserted { children[\(f.number)] = \(swiftTypeName(vField.messageType!)).buildOmniBufSchemaMeta(visited: &visited) }\n"
                }
            } else if f.type == .message {
                out += "\(indent)        if inserted { children[\(f.number)] = \(swiftTypeName(f.messageType!)).buildOmniBufSchemaMeta(visited: &visited) }\n"
            }
        }
        out += "\(indent)        return SchemaMeta(typeName: \"\(msg.name)\", fields: fields, children: children)\n"
        out += "\(indent)    }\n"
        out += "\(indent)}\n\n"

        // Lazy Opaque View & Wire Splicer
        emitOpaqueView(msg, into: &out, indent: indent)
    }

    private func emitEncodeField(_ f: FieldDescriptor, target: String, into out: inout String, indent: String) {
        let num = f.number
        if f.isMap {
            let entry = f.messageType!
            let kField = entry.fields[0]
            let vField = entry.fields[1]
            out += "\(indent)if !\(target).isEmpty {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireMap)\n"
            out += "\(indent)    let lenPos = w.reserveLength2()\n"
            out += "\(indent)    w.appendTwoBytes(\(wireTypeExpr(kField)), \(wireTypeExpr(vField)))\n"
            out += "\(indent)    w.appendVarint(UInt64(\(target).count))\n"
            if kField.type == .string {
                out += "\(indent)    if deterministic {\n"
                out += "\(indent)        for k in \(target).keys.sorted(by: compareUTF8Bytes) {\n"
                out += "\(indent)            w.appendStringValue(k)\n"
                emitAppendScalar(vField, expr: "\(target)[k]!", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    } else {\n"
                out += "\(indent)        for (k, v) in \(target) {\n"
                out += "\(indent)            w.appendStringValue(k)\n"
                emitAppendScalar(vField, expr: "v", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    }\n"
            } else if kField.type == .bool {
                out += "\(indent)    if deterministic {\n"
                out += "\(indent)        for k in \(target).keys.sorted(by: { !$0 && $1 }) {\n"
                emitAppendScalar(kField, expr: "k", into: &out, indent: indent + "            ")
                emitAppendScalar(vField, expr: "\(target)[k]!", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    } else {\n"
                out += "\(indent)        for (k, v) in \(target) {\n"
                emitAppendScalar(kField, expr: "k", into: &out, indent: indent + "            ")
                emitAppendScalar(vField, expr: "v", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    }\n"
            } else {
                out += "\(indent)    if deterministic {\n"
                out += "\(indent)        for k in \(target).keys.sorted() {\n"
                emitAppendScalar(kField, expr: "k", into: &out, indent: indent + "            ")
                emitAppendScalar(vField, expr: "\(target)[k]!", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    } else {\n"
                out += "\(indent)        for (k, v) in \(target) {\n"
                emitAppendScalar(kField, expr: "k", into: &out, indent: indent + "            ")
                emitAppendScalar(vField, expr: "v", into: &out, indent: indent + "            ")
                out += "\(indent)        }\n"
                out += "\(indent)    }\n"
            }
            out += "\(indent)    w.backpatchLength2(at: lenPos)\n"
            out += "\(indent)}\n"
            return
        }

        if f.isRepeated {
            out += "\(indent)if !\(target).isEmpty {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireArray)\n"
            if f.type == .message {
                out += "\(indent)    var arrEst = 8\n"
                out += "\(indent)    for elem in \(target) { arrEst &+= elem.estimatedOmniBufSize &+ 4 }\n"
                out += "\(indent)    if arrEst > 16_383 {\n"
                out += "\(indent)        let lenPos = w.reserveLength4()\n"
                out += "\(indent)        w.appendByte(\(wireTypeExpr(f)))\n"
                out += "\(indent)        w.appendVarint(UInt64(\(target).count))\n"
                out += "\(indent)        for elem in \(target) {\n"
                out += "\(indent)            if elem.estimatedOmniBufSize > 16_383 {\n"
                out += "\(indent)                let elemLenPos = w.reserveLength4()\n"
                out += "\(indent)                elem.encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
                out += "\(indent)                w.backpatchLength4(at: elemLenPos)\n"
                out += "\(indent)            } else {\n"
                out += "\(indent)                let elemLenPos = w.reserveLength2()\n"
                out += "\(indent)                elem.encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
                out += "\(indent)                w.backpatchLength2(at: elemLenPos)\n"
                out += "\(indent)            }\n"
                out += "\(indent)        }\n"
                out += "\(indent)        w.backpatchLength4(at: lenPos)\n"
                out += "\(indent)    } else {\n"
                out += "\(indent)        let lenPos = w.reserveLength2()\n"
                out += "\(indent)        w.appendByte(\(wireTypeExpr(f)))\n"
                out += "\(indent)        w.appendVarint(UInt64(\(target).count))\n"
                out += "\(indent)        for elem in \(target) {\n"
                out += "\(indent)            let elemLenPos = w.reserveLength2()\n"
                out += "\(indent)            elem.encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
                out += "\(indent)            w.backpatchLength2(at: elemLenPos)\n"
                out += "\(indent)        }\n"
                out += "\(indent)        w.backpatchLength2(at: lenPos)\n"
                out += "\(indent)    }\n"
            } else {
                out += "\(indent)    let lenPos = w.reserveLength2()\n"
                out += "\(indent)    w.appendByte(\(wireTypeExpr(f)))\n"
                out += "\(indent)    w.appendVarint(UInt64(\(target).count))\n"
                out += "\(indent)    for elem in \(target) {\n"
                emitAppendScalar(f, expr: "elem", into: &out, indent: indent + "        ")
                out += "\(indent)    }\n"
                out += "\(indent)    w.backpatchLength2(at: lenPos)\n"
            }
            out += "\(indent)}\n"
            return
        }

        switch f.type {
        case .message:
            out += "\(indent)if let sub = \(target) {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireSubMsg)\n"
            out += "\(indent)    if sub.estimatedOmniBufSize > 16_383 {\n"
            out += "\(indent)        let lenPos = w.reserveLength4()\n"
            out += "\(indent)        sub.encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
            out += "\(indent)        w.backpatchLength4(at: lenPos)\n"
            out += "\(indent)    } else {\n"
            out += "\(indent)        let lenPos = w.reserveLength2()\n"
            out += "\(indent)        sub.encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
            out += "\(indent)        w.backpatchLength2(at: lenPos)\n"
            out += "\(indent)    }\n"
            out += "\(indent)}\n"
        case .bool:
            out += "\(indent)if \(target) {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireBoolTrue)\n"
            out += "\(indent)}\n"
        case .string:
            out += "\(indent)if !\(target).isEmpty {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireString)\n"
            out += "\(indent)    w.appendStringValue(\(target))\n"
            out += "\(indent)}\n"
        case .bytes:
            out += "\(indent)if !\(target).isEmpty {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireBytes)\n"
            out += "\(indent)    w.appendBytes(\(target))\n"
            out += "\(indent)}\n"
        case .float:
            out += "\(indent)if \(target).bitPattern != 0 {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireFloat32)\n"
            out += "\(indent)    w.appendFloat32(\(target))\n"
            out += "\(indent)}\n"
        case .double:
            out += "\(indent)if \(target).bitPattern != 0 {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: WireType.wireFloat64)\n"
            out += "\(indent)    w.appendFloat64(\(target))\n"
            out += "\(indent)}\n"
        default:
            out += "\(indent)if \(target) != 0 {\n"
            out += "\(indent)    w.appendTag(fieldNumber: \(num), wireType: \(wireTypeExpr(f)))\n"
            emitAppendScalar(f, expr: target, into: &out, indent: indent + "    ")
            out += "\(indent)}\n"
        }
    }

    private func emitAppendScalar(_ f: FieldDescriptor, expr: String, into out: inout String, indent: String) {
        switch f.type {
        case .uint32: out += "\(indent)w.appendVarint(UInt64(\(expr)))\n"
        case .uint64: out += "\(indent)w.appendVarint(\(expr))\n"
        case .int32, .sint32, .enum: out += "\(indent)w.appendZigZag32(\(expr))\n"
        case .int64, .sint64: out += "\(indent)w.appendZigZag(\(expr))\n"
        case .bool: out += "\(indent)w.appendByte(\(expr) ? 1 : 0)\n"
        case .fixed32: out += "\(indent)w.appendFixed32(\(expr))\n"
        case .fixed64: out += "\(indent)w.appendFixed64(\(expr))\n"
        case .sfixed32: out += "\(indent)w.appendSfixed32(\(expr))\n"
        case .sfixed64: out += "\(indent)w.appendSfixed64(\(expr))\n"
        case .float: out += "\(indent)w.appendFloat32(\(expr))\n"
        case .double: out += "\(indent)w.appendFloat64(\(expr))\n"
        case .string: out += "\(indent)w.appendStringValue(\(expr))\n"
        case .bytes: out += "\(indent)w.appendBytes(\(expr))\n"
        case .message:
            out += "\(indent)let subLenPos = w.reserveLength2()\n"
            out += "\(indent)\(expr).encodeOmniBufBodyFast(into: &w, deterministic: deterministic)\n"
            out += "\(indent)w.backpatchLength2(at: subLenPos)\n"
        default: break
        }
    }

    private func emitDecodeField(_ f: FieldDescriptor, into out: inout String, indent: String) {
        let p = camelCase(f.name)
        out += "\(indent)case \(f.number):\n"
        if f.isMap {
            let entry = f.messageType!
            let kField = entry.fields[0]
            let vField = entry.fields[1]
            out += "\(indent)    guard wt == WireType.wireMap else {\n"
            out += "\(indent)        try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
            out += "\(indent)        continue\n"
            out += "\(indent)    }\n"
            out += "\(indent)    let mapDepth = depth &+ 1\n"
            out += "\(indent)    guard mapDepth <= budget.maxDepth else { throw OmniBufError.depthLimitExceeded(mapDepth) }\n"
            out += "\(indent)    let body = try r.readLenSlice(minLen: 3)\n"
            out += "\(indent)    let (keyWT, valWT, count, mr0) = try OmniBufReader.parseMapBody(body)\n"
            out += "\(indent)    guard keyWT == \(wireTypeExpr(kField)) && valWT == \(wireTypeExpr(vField)) else {\n"
            out += "\(indent)        throw OmniBufError.parse(\"field \(f.number) map type mismatch\")\n"
            out += "\(indent)    }\n"
            out += "\(indent)    try budget.addElements(count)\n"
            out += "\(indent)    try budget.addAlloc(count: count, elementBytes: 32)\n"
            out += "\(indent)    var mr = mr0\n"
            out += "\(indent)    for _ in 0..<count {\n"
            out += "\(indent)        let k = \(readScalarExpr(kField, reader: "mr"))\n"
            if kField.type == .string {
                out += "\(indent)        try budget.addAlloc(k.utf8.count)\n"
            }
            if vField.type == .message {
                out += "\(indent)        let valDepth = mapDepth &+ 1\n"
                out += "\(indent)        guard valDepth <= budget.maxDepth else { throw OmniBufError.depthLimitExceeded(valDepth) }\n"
                out += "\(indent)        let slice = try mr.readLenSlice()\n"
                out += "\(indent)        var v = \(swiftTypeName(vField.messageType!))()\n"
                out += "\(indent)        try v.mergeOmniBuf(from: slice, depth: valDepth, budget: &budget)\n"
            } else {
                out += "\(indent)        let v = \(readScalarExpr(vField, reader: "mr"))\n"
                if vField.type == .string {
                    out += "\(indent)        try budget.addAlloc(v.utf8.count)\n"
                } else if vField.type == .bytes {
                    out += "\(indent)        try budget.addAlloc(v.count)\n"
                }
            }
            out += "\(indent)        self.\(p)[k] = v\n"
            out += "\(indent)    }\n"
            out += "\(indent)    guard mr.isAtEnd else { throw OmniBufError.parse(\"WireMap trailing bytes\") }\n"
            return
        }

        if f.isRepeated {
            let elemType = swiftSingularBaseType(f)
            let elemBytesExpr = f.type == .message
                ? "max(MemoryLayout<\(elemType)>.stride, 16)"
                : "max(MemoryLayout<\(elemType)>.stride, 1)"
            out += "\(indent)    guard wt == WireType.wireArray else {\n"
            out += "\(indent)        try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
            out += "\(indent)        continue\n"
            out += "\(indent)    }\n"
            out += "\(indent)    let arrDepth = depth &+ 1\n"
            out += "\(indent)    guard arrDepth <= budget.maxDepth else { throw OmniBufError.depthLimitExceeded(arrDepth) }\n"
            out += "\(indent)    let body = try r.readLenSlice(minLen: 2)\n"
            out += "\(indent)    let (elemWT, count, er0) = try OmniBufReader.parseArrayBody(body)\n"
            out += "\(indent)    guard elemWT == \(wireTypeExpr(f)) else {\n"
            out += "\(indent)        throw OmniBufError.parse(\"field \(f.number) array element type mismatch\")\n"
            out += "\(indent)    }\n"
            out += "\(indent)    try budget.addElements(count)\n"
            out += "\(indent)    try budget.addAlloc(count: count, elementBytes: \(elemBytesExpr))\n"
            out += "\(indent)    let (newCap, capOverflow) = self.\(p).count.addingReportingOverflow(count)\n"
            out += "\(indent)    if capOverflow { throw OmniBufError.allocationLimitExceeded(\"array capacity overflow\") }\n"
            out += "\(indent)    var er = er0\n"
            out += "\(indent)    self.\(p).reserveCapacity(newCap)\n"
            out += "\(indent)    for _ in 0..<count {\n"
            if f.type == .message {
                out += "\(indent)        let elemDepth = arrDepth &+ 1\n"
                out += "\(indent)        guard elemDepth <= budget.maxDepth else { throw OmniBufError.depthLimitExceeded(elemDepth) }\n"
                out += "\(indent)        let slice = try er.readLenSlice()\n"
                out += "\(indent)        var elem = \(swiftTypeName(f.messageType!))()\n"
                out += "\(indent)        try elem.mergeOmniBuf(from: slice, depth: elemDepth, budget: &budget)\n"
                out += "\(indent)        self.\(p).append(elem)\n"
            } else {
                out += "\(indent)        let elem = \(readScalarExpr(f, reader: "er"))\n"
                if f.type == .string {
                    out += "\(indent)        try budget.addAlloc(elem.utf8.count)\n"
                } else if f.type == .bytes {
                    out += "\(indent)        try budget.addAlloc(elem.count)\n"
                }
                out += "\(indent)        self.\(p).append(elem)\n"
            }
            out += "\(indent)    }\n"
            out += "\(indent)    guard er.isAtEnd else { throw OmniBufError.parse(\"WireArray trailing bytes\") }\n"
            return
        }

        if f.type == .bool {
            out += "\(indent)    if wt == WireType.wireBoolFalse {\n"
            out += "\(indent)        self.\(p) = false\n"
            out += "\(indent)    } else if wt == WireType.wireBoolTrue {\n"
            out += "\(indent)        self.\(p) = true\n"
            out += "\(indent)    } else {\n"
            out += "\(indent)        try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
            out += "\(indent)    }\n"
            return
        }

        if f.type == .message {
            out += "\(indent)    guard wt == WireType.wireSubMsg else {\n"
            out += "\(indent)        try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
            out += "\(indent)        continue\n"
            out += "\(indent)    }\n"
            out += "\(indent)    let nextDepth = depth &+ 1\n"
            out += "\(indent)    guard nextDepth <= budget.maxDepth else { throw OmniBufError.depthLimitExceeded(nextDepth) }\n"
            out += "\(indent)    let slice = try r.readLenSlice()\n"
            out += "\(indent)    var sub = self.\(p) ?? \(swiftTypeName(f.messageType!))()\n"
            out += "\(indent)    try sub.mergeOmniBuf(from: slice, depth: nextDepth, budget: &budget)\n"
            out += "\(indent)    self.\(p) = sub\n"
            return
        }

        out += "\(indent)    guard wt == \(wireTypeExpr(f)) else {\n"
        out += "\(indent)        try r.validateValue(wireType: wt, inCollection: false, depth: depth, maxDepth: budget.maxDepth)\n"
        out += "\(indent)        continue\n"
        out += "\(indent)    }\n"
        out += "\(indent)    let val = \(readScalarExpr(f, reader: "r"))\n"
        if f.type == .string {
            out += "\(indent)    try budget.addAlloc(val.utf8.count)\n"
        } else if f.type == .bytes {
            out += "\(indent)    try budget.addAlloc(val.count)\n"
        }
        out += "\(indent)    self.\(p) = val\n"
    }

    private func readScalarExpr(_ f: FieldDescriptor, reader: String) -> String {
        switch f.type {
        case .uint32: return "UInt32(truncatingIfNeeded: try \(reader).readVarint())"
        case .uint64: return "try \(reader).readVarint()"
        case .int32, .sint32, .enum: return "try \(reader).readSint32()"
        case .int64, .sint64: return "try \(reader).readSint64()"
        case .bool: return "try \(reader).readBoolByte()"
        case .fixed32: return "try \(reader).readFixed32()"
        case .fixed64: return "try \(reader).readFixed64()"
        case .sfixed32: return "try \(reader).readSfixed32()"
        case .sfixed64: return "try \(reader).readSfixed64()"
        case .float: return "try \(reader).readFloat32()"
        case .double: return "try \(reader).readFloat64()"
        case .string: return "try \(reader).readString()"
        case .bytes: return "try \(reader).readBytes()"
        default: return "try \(reader).readSint32()"
        }
    }

    // MARK: - Lazy Opaque View & Splicer Generation

    private func emitOpaqueView(_ msg: Descriptor, into out: inout String, indent: String) {
        let name = swiftTypeName(msg)
        let opaqueName = "Opaque\(name)"
        let fields = msg.fields.sorted { $0.number < $1.number }
        let maxFieldNum = fields.map(\.number).max() ?? 0
        let hasHighFields = fields.contains { $0.number >= 64 }

        out += "\(indent)public struct \(opaqueName): Sendable {\n"
        out += "\(indent)    public let raw: [UInt8]\n"
        out += "\(indent)    public let offset: Int\n"
        out += "\(indent)    public let length: Int\n"
        out += "\(indent)    @usableFromInline internal var dirtyMask: UInt64 = 0\n"
        if hasHighFields {
            out += "\(indent)    @usableFromInline internal var dirtyHigh: Set<UInt32> = []\n"
        }
        for f in fields {
            out += "\(indent)    @usableFromInline internal var dirty_\(f.name): \(swiftFieldType(f)) = \(defaultValue(f))\n"
        }
        out += "\n\(indent)    @inlinable\n"
        out += "\(indent)    public init(_ raw: [UInt8]) {\n"
        out += "\(indent)        self.raw = raw\n"
        out += "\(indent)        self.offset = 0\n"
        out += "\(indent)        self.length = raw.count\n"
        out += "\(indent)    }\n\n"
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public init(raw: [UInt8], offset: Int, length: Int) {\n"
        out += "\(indent)        precondition(offset >= 0 && length >= 0 && offset <= raw.count && length <= raw.count - offset, \"\(opaqueName) slice out of bounds\")\n"
        out += "\(indent)        self.raw = raw\n"
        out += "\(indent)        self.offset = offset\n"
        out += "\(indent)        self.length = length\n"
        out += "\(indent)    }\n\n"
        out += "\(indent)    @inlinable\n"
        out += "\(indent)    @inline(__always)\n"
        out += "\(indent)    internal func withSlice<R>(_ body: (UnsafeBufferPointer<UInt8>) -> R) -> R {\n"
        out += "\(indent)        raw.withUnsafeBufferPointer { buf in\n"
        out += "\(indent)            body(UnsafeBufferPointer(start: buf.baseAddress?.advanced(by: offset), count: length))\n"
        out += "\(indent)        }\n"
        out += "\(indent)    }\n\n"

        // Getters & Setters
        for f in fields {
            let pName = pascalCase(f.name)
            let num = f.number
            let isDirtyExpr = num < 64 ? "(dirtyMask & (1 &<< \(num))) != 0" : "dirtyHigh.contains(\(num))"
            let markDirtyStmt = num < 64 ? "dirtyMask |= (1 &<< \(num))" : "dirtyHigh.insert(\(num))"

            if f.isMap {
                let entry = f.messageType!
                if entry.fields[0].type == .string && entry.fields[1].type == .uint64 {
                    out += "\(indent)    @inlinable\n"
                    out += "\(indent)    public func lookup\(pName)(_ key: String) -> UInt64? {\n"
                    out += "\(indent)        if \(isDirtyExpr) { return dirty_\(f.name)[key] }\n"
                    out += "\(indent)        return withSlice { OpaqueWire.lookupMapStringUint64(in: $0, fieldNumber: \(num), key: key) }\n"
                    out += "\(indent)    }\n"
                }
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public mutating func set\(pName)(_ value: \(swiftFieldType(f))) {\n"
                out += "\(indent)        dirty_\(f.name) = value\n"
                out += "\(indent)        \(markDirtyStmt)\n"
                out += "\(indent)    }\n"
            } else if f.isRepeated {
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public var \(camelCaseRaw(f.name))Count: Int {\n"
                out += "\(indent)        if \(isDirtyExpr) { return dirty_\(f.name).count }\n"
                out += "\(indent)        return withSlice { OpaqueWire.arrayCount(in: $0, fieldNumber: \(num), expectedElemType: \(wireTypeExpr(f))) }\n"
                out += "\(indent)    }\n"
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public mutating func set\(pName)(_ value: \(swiftFieldType(f))) {\n"
                out += "\(indent)        dirty_\(f.name) = value\n"
                out += "\(indent)        \(markDirtyStmt)\n"
                out += "\(indent)    }\n"
            } else if f.type == .message {
                let subName = swiftTypeName(f.messageType!)
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public func get\(pName)() -> Opaque\(subName) {\n"
                out += "\(indent)        if \(isDirtyExpr) {\n"
                out += "\(indent)            return Opaque\(subName)(dirty_\(f.name)?.marshalOmniBuf() ?? [])\n"
                out += "\(indent)        }\n"
                out += "\(indent)        return withSlice { slice in\n"
                out += "\(indent)            guard let loc = OpaqueWire.locateSubMsgRange(in: slice, fieldNumber: \(num)) else {\n"
                out += "\(indent)                return Opaque\(subName)(raw: [], offset: 0, length: 0)\n"
                out += "\(indent)            }\n"
                out += "\(indent)            if !loc.multiple {\n"
                out += "\(indent)                return Opaque\(subName)(raw: raw, offset: offset &+ loc.start, length: loc.end &- loc.start)\n"
                out += "\(indent)            }\n"
                out += "\(indent)            return Opaque\(subName)(OpaqueWire.readMergedSubMsgBytes(in: slice, fieldNumber: \(num)))\n"
                out += "\(indent)        }\n"
                out += "\(indent)    }\n"
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public mutating func set\(pName)(_ value: \(subName)?) {\n"
                out += "\(indent)        dirty_\(f.name) = value\n"
                out += "\(indent)        \(markDirtyStmt)\n"
                out += "\(indent)    }\n"
            } else {
                let readFn: String
                switch f.type {
                case .uint32: readFn = "readUint32"
                case .uint64: readFn = "readUint64"
                case .int32, .sint32, .enum: readFn = "readSint32"
                case .int64, .sint64: readFn = "readSint64"
                case .bool: readFn = "readBool"
                case .fixed32: readFn = "readFixed32"
                case .fixed64: readFn = "readFixed64"
                case .sfixed32: readFn = "readSfixed32"
                case .sfixed64: readFn = "readSfixed64"
                case .float: readFn = "readFloat32"
                case .double: readFn = "readFloat64"
                case .string: readFn = "readString"
                case .bytes: readFn = "readBytes"
                default: readFn = "readUint32"
                }
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public func get\(pName)() -> \(swiftFieldType(f)) {\n"
                out += "\(indent)        if \(isDirtyExpr) { return dirty_\(f.name) }\n"
                out += "\(indent)        return withSlice { OpaqueWire.\(readFn)(in: $0, fieldNumber: \(num)) }\n"
                out += "\(indent)    }\n"
                out += "\(indent)    @inlinable\n"
                out += "\(indent)    public mutating func set\(pName)(_ value: \(swiftFieldType(f))) {\n"
                out += "\(indent)        dirty_\(f.name) = value\n"
                out += "\(indent)        \(markDirtyStmt)\n"
                out += "\(indent)    }\n"
            }
        }

        // Dirty field encoder + marshal / tryMarshal
        out += "\n\(indent)    @inlinable\n"
        out += "\(indent)    internal func appendDirtyField(_ fnum: UInt32, into w: inout OmniBufWriter) {\n"
        out += "\(indent)        let deterministic = true\n"
        out += "\(indent)        _ = deterministic\n"
        out += "\(indent)        switch fnum {\n"
        for f in fields {
            out += "\(indent)        case \(f.number):\n"
            emitEncodeField(f, target: "self.dirty_\(f.name)", into: &out, indent: indent + "            ")
        }
        out += "\(indent)        default:\n"
        out += "\(indent)            break\n"
        out += "\(indent)        }\n"
        out += "\(indent)    }\n\n"

        let cleanCond = hasHighFields ? "dirtyMask == 0 && dirtyHigh.isEmpty" : "dirtyMask == 0"
        let dirtyHighArg = hasHighFields ? ", dirtyHigh: dirtyHigh" : ""

        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public func marshal() -> [UInt8] {\n"
        out += "\(indent)        if \(cleanCond) {\n"
        out += "\(indent)            if offset == 0 && length == raw.count { return raw }\n"
        out += "\(indent)            return Array(raw[offset..<(offset + length)])\n"
        out += "\(indent)        }\n"
        out += "\(indent)        var dst: [UInt8] = []\n"
        out += "\(indent)        OpaqueWire.spliceFields(into: &dst, raw: raw, offset: offset, length: length, dirtyMask: dirtyMask\(dirtyHighArg), maxField: \(maxFieldNum)) { w, fnum in\n"
        out += "\(indent)            self.appendDirtyField(fnum, into: &w)\n"
        out += "\(indent)        }\n"
        out += "\(indent)        return dst\n"
        out += "\(indent)    }\n\n"

        out += "\(indent)    @inlinable\n"
        out += "\(indent)    public func tryMarshal() throws -> [UInt8] {\n"
        out += "\(indent)        var dst: [UInt8] = []\n"
        out += "\(indent)        try OpaqueWire.trySpliceFields(into: &dst, raw: raw, offset: offset, length: length, dirtyMask: dirtyMask\(dirtyHighArg), maxField: \(maxFieldNum)) { w, fnum in\n"
        out += "\(indent)            self.appendDirtyField(fnum, into: &w)\n"
        out += "\(indent)        }\n"
        out += "\(indent)        return dst\n"
        out += "\(indent)    }\n"
        out += "\(indent)}\n\n"
    }
}
